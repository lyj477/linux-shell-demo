# 前言
跟着韩顺平Linux课程学习Shell脚本，写一个运维日常服务器巡检小脚本，适合新手练习，后续可以持续迭代优化，脚本已上传GitHub。

## 1、脚本功能
1. 打印系统当前时间
2. 查看内存使用情况
3. 查看磁盘占用
4. 查看系统负载
5. 查看本机监听端口

## 2、完整脚本代码
```bash
#!/bin/bash
# 基础服务器巡检脚本
echo "=========当前系统时间========"
date
echo "=========内存信息========"
free -h
echo "=========磁盘信息========"
df -h
echo "=========负载信息========"
uptime
echo "=========监听端口========"
ss -ltnp
